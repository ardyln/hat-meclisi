export let lang = storageGet('hm-lang') || ((navigator.language || 'tr').toLowerCase().startsWith('tr') ? 'tr' : 'en');

export function setLang(l) {
  lang = TEXT[l] ? l : 'tr';
  storageSet('hm-lang', lang);
  document.documentElement.lang = lang;
}

export function t(key, vars) {
  let s = TEXT[lang][key] ?? TEXT.tr[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v);
  return s;
}

export const fmt = (n, digits = 1) => new Intl.NumberFormat(lang === 'tr' ? 'tr-TR' : 'en-GB', { maximumFractionDigits: digits, minimumFractionDigits: digits }).format(n);

export function ago(ms) {
  const s = Math.max(0, (Date.now() - ms) / 1000);
  if (s < 60) return t('justNow');
  if (s < 3600) return t('minAgo', { n: Math.floor(s / 60) });
  if (s < 86400) return t('hourAgo', { n: Math.floor(s / 3600) });
  return t('dayAgo', { n: Math.floor(s / 86400) });
}

export function date(ms) {
  return ms ? new Date(ms).toLocaleDateString(lang === 'tr' ? 'tr-TR' : 'en-GB', { day: 'numeric', month: 'short', year: 'numeric' }) : '';
}
